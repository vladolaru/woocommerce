#!/usr/bin/env bash
# Lists the shared contract of the kept modules at the fork point: hooks fired, options read or written,
# REST routes, script and style handles, gateway IDs, admin note sources and global constants.
# Usage: contract-list.sh [--out <path>|--out -] <extension clone>   (--out may also follow the clone path; extra arguments are rejected)
# Writes the appendix itself, so never redirect its output into the appendix: a shell redirection truncates the file before
# any check can run. The script generates into a temporary file and replaces the target only when generation succeeded.
# Line 1 carries the extension commit and no timestamp, so a regeneration at the same commit is byte-identical.
# The last section lists the names core owns (the collecting state), scanned from this plugin's PayPal tree, so it changes only when core's names do.
# --out defaults to src/Internal/Payments/Providers/PayPal/contract-appendix.md in this plugin; "--out -" prints to stdout.
set -euo pipefail
# Sort order depends on the caller's locale; pin it so every machine generates the same bytes.
export LC_ALL=C
HERE="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
CORE_PP="$HERE/../../src/Internal/Payments/Providers/PayPal"
OUT="$CORE_PP/contract-appendix.md"
USAGE="usage: contract-list.sh [--out <path>|--out -] <extension clone>"
EXT=""
OUT_SET=0
while [ $# -gt 0 ]; do
  case "$1" in
    --out)
      [ $# -ge 2 ] || { echo "$USAGE" >&2; exit 1; }
      [ "$OUT_SET" = 0 ] || { echo "--out given twice" >&2; echo "$USAGE" >&2; exit 1; }
      [ -n "$2" ] || { echo "--out needs a path or -" >&2; echo "$USAGE" >&2; exit 1; }
      OUT="$2"; OUT_SET=1; shift 2 ;;
    -*) # "-" alone is not an option name either; anything starting with a dash is rejected here.
      echo "unknown option: $1" >&2; echo "$USAGE" >&2; exit 1 ;;
    *)
      [ -z "$EXT" ] || { echo "unexpected argument: $1" >&2; echo "$USAGE" >&2; exit 1; }
      EXT="$1"; shift ;;
  esac
done
[ -n "$EXT" ] || { echo "$USAGE" >&2; exit 1; }
[ ! -d "$OUT" ] || { echo "--out is a directory, give a file path: $OUT" >&2; exit 1; }
SHORT="$(git -C "$EXT" rev-parse --short HEAD 2>/dev/null)" || { echo "not a git clone: $EXT" >&2; exit 1; }
test -d "$EXT/modules" || { echo "not the PayPal Payments extension (no modules/ directory): $EXT" >&2; exit 1; }
KEPT="woocommerce-logging ppcp-admin-notices ppcp-api-client ppcp-blocks ppcp-button ppcp-compat ppcp-order-endpoints ppcp-paylater-block ppcp-paylater-configurator ppcp-paylater-wc-blocks ppcp-save-payment-methods ppcp-sdk-v6 ppcp-session ppcp-settings ppcp-vault-component ppcp-wc-gateway ppcp-wc-payment-tokens ppcp-wc-subscriptions ppcp-webhooks"
PATHS=("$EXT/src" "$EXT/lib/common" "$EXT/woocommerce-paypal-payments.php" "$EXT/bootstrap.php")
for m in $KEPT; do PATHS+=("$EXT/modules/$m"); done

# Generate into a temporary file; the target is touched only after everything below succeeded.
if [ "$OUT" = "-" ]; then
  TMP="$(mktemp)"
else
  TMP="$(mktemp "$OUT.XXXXXX")" || { echo "cannot write beside $OUT" >&2; exit 1; }
fi
trap 'rm -f "$TMP"' EXIT
exec 3>&1 1>"$TMP"

# grep exits 1 when nothing matches (fine for a section) and 2 on a real error (a missing path), which must fail the script.
scan() { grep -rhoE "$1" "${PATHS[@]}" --include='*.php' || [ $? -eq 1 ]; }

# The same scan over core's own PayPal tree (the shell, Collecting/ and the seam hooks in Wallet/).
cscan() { grep -rhoE "$1" "$CORE_PP" --include='*.php' || [ $? -eq 1 ]; }

section() { printf '\n## %s\n\n' "$1"; }
list() { sort -u | sed 's/^/- `/; s/$/`/'; }

echo "# Shared-contract appendix (generated from $SHORT)"
echo
echo "Names the fork keeps name-for-name and format-for-format (spec §2). Generated by \`bin/paypal-wallet-fork/contract-list.sh\`; regenerate rather than edit. It lists the names at the fork point; the section \"Names stopped in core\" in \`FORK.md\` lists the ones core has since stopped using. The last section lists the names core added, which the extension does not have."

section "Hooks fired (actions and filters)"
scan "(apply_filters|do_action|apply_filters_deprecated|do_action_deprecated)\(\s*'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list

section "Options read or written"
scan "(get_option|update_option|delete_option|add_option)\(\s*'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list
echo
echo "Option prefixes built at runtime (\`woocommerce_{gateway id}_settings\`, \`ppcp-*\` transients) are covered by the gateway IDs below; \`OPTION_KEY\` and \`OPTION_NAME\` constants:"
scan "const OPTION[A-Z_]* *= *'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list

section "Other string constants naming stored keys (KEY, TRANSIENT, NONCE and similar)"
scan "const [A-Z_]+ *= *'(woocommerce[-_])?_?ppcp[-_][^']*'" | sed -E "s/.*'([^']+)'/\1/" | list
scan "const (KEY|[A-Z_]*TRANSIENT[A-Z_]*|[A-Z_]*NONCE[A-Z_]*|[A-Z_]*_KEY) *= *'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list

section "REST routes"
scan "register_rest_route\(\s*[^,]+,\s*'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list
scan "const (NAMESPACE|ROUTE|REST_NAMESPACE|ENDPOINT)[A-Z_]* *= *'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list

section "Script and style handles"
scan "(wp_register_script|wp_enqueue_script|wp_register_style|wp_enqueue_style)\(\s*'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list
scan "get_asset_handle\(\s*'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | sed 's/^/{module}-/' | list

section "Gateway and payment method IDs"
scan "const ID *= *'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list

section "Order and token meta keys"
scan "const [A-Z_]*META[A-Z_]* *= *'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list
scan "(update_meta_data|get_meta|add_meta_data|delete_meta_data)\(\s*'[^']+'" | sed -E "s/.*'([^']+)'/\1/" | list

section "Admin note source and global constants"
echo '- `woocommerce-paypal-payments` (inbox note source, `InboxNoteRegistrar`; the fork keeps it through `WalletProperties::baseName()`)'
{ grep -hoE "define\( '[A-Z_]+'" "$EXT/woocommerce-paypal-payments.php" || [ $? -eq 1 ]; } | sed -E "s/.*'([^']+)'/\1/" | list

section "Core-owned names (the collecting state)"
echo 'Names core owns and the extension does not know: the shell, `Collecting/`, the five PHP seams in `Wallet/` (three hooks) and the two core files that fire the provider notice and refund lock filters (see "Seams for the after-payment flow" in `FORK.md`). Scanned from this plugin'"'"'s own tree, never from the extension. They carry the `woocommerce_paypal_wallet` and `wc_paypal_wallet` prefixes, never `ppcp`.'
echo
echo 'Hooks fired:'
echo
HOOK_RE="(apply_filters|do_action|apply_filters_deprecated|do_action_deprecated)\(\s*'woocommerce_paypal_wallet_[^']+'"
# Two core files outside the PayPal tree fire core-owned hooks: the provider class and the order items view.
{ cscan "$HOOK_RE"; grep -hoE "$HOOK_RE" "$HERE/../../src/Internal/Admin/Settings/PaymentsProviders/PayPal.php" "$HERE/../../includes/admin/meta-boxes/views/html-order-items.php" || [ $? -eq 1 ]; } | sed -E "s/.*'([^']+)'/\1/" | list
echo
echo 'Names held in constants (options, transient and lock-row prefixes, order and user meta keys, the AJAX action, email IDs, the cron hook):'
echo
cscan "const [A-Z_]+ *= *'_?(woocommerce_paypal_wallet|wc_paypal_wallet)_[^']*'" | sed -E "s/.*'([^']+)'/\1/" | list
echo
echo 'Names built or returned at runtime (transient prefixes per platform app, the last-webhook option):'
echo
RUNTIME_NAMES="$( { cscan "'wc_paypal_wallet_[a-z_]+_' *\. *\\$"; cscan "\? *'wc_paypal_wallet_[a-z_]+' *: *\\\$previous"; } | sed -E "s/.*'(wc_paypal_wallet_[a-z_]+)'.*/\1/" | sort -u )"
# These names are found by the shape of the code that builds them; if a refactor hides one, fail instead of dropping it silently.
for expected in wc_paypal_wallet_bearer_ wc_paypal_wallet_rate_ wc_paypal_wallet_last_webhook; do
  printf '%s\n' "$RUNTIME_NAMES" | grep -qxF "$expected" || { echo "contract-list.sh: expected core-owned name not found: $expected" >&2; exit 1; }
done
printf '%s\n' "$RUNTIME_NAMES" | list
echo
echo 'REST namespace and routes (all `manage_woocommerce`):'
echo
{ grep -rhoE "const NAMESPACE *= *'[^']+'" "$CORE_PP/Collecting" --include='*.php' || [ $? -eq 1 ]; } | sed -E "s/.*'([^']+)'/\1/" | list
# The routes are registered over several lines, so read each file whole.
find "$CORE_PP/Collecting" -name '*.php' -print0 | xargs -0 perl -0777 -ne 'print "$1\n" while /register_rest_route\(\s*[^,]+,\s*\x27([^\x27]+)\x27/g' | list
echo
echo 'WP-CLI commands:'
echo
cscan "'wc paypal-wallet [a-z-]+'" | sed -E "s/.*'([^']+)'/\1/" | list
echo
echo 'Script data:'
echo
{ grep -rhoE "window\.ppcpSettings\.[a-z_]+" "$CORE_PP/Collecting" --include='*.php' || [ $? -eq 1 ]; } | sed -E 's/^window\.//' | list
echo
echo 'Writes into the extension'"'"'s shared state: the only one from `Collecting/` is `GatewaySwitch::save_enabled()`, which sets `enabled = yes` in `woocommerce_ppcp-gateway_settings` through the gateway'"'"'s own settings API when a store enters the collecting state. Nothing in `Collecting/` writes `woocommerce-ppcp-data-*` or `ppcp-webhook`.'

exec 1>&3 3>&-
if [ "$OUT" = "-" ]; then
  cat "$TMP"
else
  chmod 644 "$TMP"
  mv "$TMP" "$OUT"
fi
